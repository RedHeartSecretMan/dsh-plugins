    /**
     * Derive the one-line summary a `/title` card shows while collapsed.
     *
     * `status` answers with a multi-line report whose title line is the useful
     * summary; the other verbs answer in one line that starts by restating the
     * verb, which the row already shows as a chip.
     *
     * @param text - The settled command output.
     * @param verb - The invocation's verb.
     * @param t - Translator, used for the usage-error label.
     * @returns The line worth reading in the collapsed row.
     */
    function commandSummary(text, verb, t) {
      const lines = String(text ?? '').split('\n').map((line) => line.trim()).filter(Boolean);
      if (lines.length === 0) return '';
      // A usage hint is the body's job; the collapsed row only needs its kind.
      if (lines[0].startsWith('请用 /title')) return t('command.usage');
      if (verb === 'status') {
        const heading = lines.indexOf('当前标题');
        const titled = heading === -1 ? undefined : lines[heading + 1];
        if (titled !== undefined && titled.startsWith('来源') === false) return titled;
      }
      const first = lines[0];
      for (const leadIn of SUMMARY_LEAD_INS) {
        if (leadIn.test(first)) {
          const rest = first.replace(leadIn, '').trim();
          if (rest !== '') return rest;
        }
      }
      return first;
    }

    /** Copy text to the clipboard, falling back to a hidden selection. */
    async function copyText(text) {
      try {
        if (typeof navigator !== 'undefined' && navigator.clipboard?.writeText !== undefined) {
          await navigator.clipboard.writeText(text);
          return true;
        }
      } catch { /* the fallback below is the last resort */ }
      try {
        const area = document.createElement('textarea');
        area.value = text;
        area.setAttribute('readonly', 'readonly');
        area.style.position = 'fixed';
        area.style.opacity = '0';
        document.body.appendChild(area);
        area.select();
        const ok = document.execCommand('copy');
        document.body.removeChild(area);
        return ok;
      } catch {
        return false;
      }
    }

