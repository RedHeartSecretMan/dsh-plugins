    /**
     * Fallback parser for the multi-line text emitted by `/title status` when
     * the Host HTTP status route is not yet mounted (e.g. before a Host reload).
     * Unknown lines are retained in `extraLines` so nothing is silently dropped.
     */
    function parseStatusReport(text, t) {
      const report = {
        ruleSummary: undefined,
        builtin: { template: undefined, dateSource: undefined, types: [], topicLength: undefined },
        supplements: [],
        title: { value: undefined, kind: undefined, sourceLabel: undefined, pinStatus: undefined },
        failure: null,
        probe: undefined,
        extraLines: [],
      };
      let rawSource = '';
      let rawPin = '';
      let section = null;
      for (const rawLine of String(text ?? '').split(/\r?\n/u)) {
        const trimmed = rawLine.trim();
        if (trimmed === '') continue;
        const indented = /^\s/u.test(rawLine);
        if (!indented) {
          if (trimmed.startsWith('命名规则：')) {
            report.ruleSummary = trimmed.slice('命名规则：'.length).trim();
            section = null;
          } else if (trimmed === '内置规则') {
            section = 'builtin';
          } else if (/^补充规则（\d+）$/u.test(trimmed)) {
            section = 'supplemental';
          } else if (trimmed === '当前标题') {
            section = 'title';
          } else if (trimmed.startsWith('最近失败：')) {
            const detail = trimmed.slice('最近失败：'.length).trim();
            const parts = detail.split('，').map(s => s.trim()).filter(Boolean);
            report.failure = {
              category: parts[0] ?? detail,
              meta: parts.length > 1 ? parts.slice(1).join(' · ') : undefined,
              advice: undefined,
            };
            section = 'failure';
          } else if (trimmed.startsWith('探针结论：')) {
            const verdictText = trimmed.slice('探针结论：'.length).trim();
            report.probe = {
              text: verdictText,
              healthy: !verdictText.includes('丢弃') && !verdictText.includes('未送达'),
            };
            section = null;
          } else {
            report.extraLines.push(trimmed);
            section = null;
          }
          continue;
        }
        if (section === 'builtin') {
          const kv = trimmed.match(/^(标题格式|日期来源|类型词表|主题长度)\s+(.+)$/u);
          if (kv) {
            const [, label, value] = kv;
            if (label === '标题格式') report.builtin.template = value.trim();
            else if (label === '日期来源') report.builtin.dateSource = value.trim();
            else if (label === '类型词表') report.builtin.types = value.split('、').map(s => s.trim()).filter(Boolean);
            else if (label === '主题长度') report.builtin.topicLength = value.trim();
          } else {
            report.extraLines.push(trimmed);
          }
        } else if (section === 'supplemental') {
          report.supplements.push(trimmed);
        } else if (section === 'title') {
          // The first indented line under `当前标题` is always the title value
          // itself (`renderTitleStatus` writes it before `来源：` and `状态：`),
          // so a title starting with those words is never misclassified.
          if (report.title.value === undefined && rawSource === '' && rawPin === '') {
            report.title.value = trimmed === '尚无标题' ? undefined : trimmed;
          } else if (trimmed.startsWith('来源：')) {
            rawSource = trimmed.slice('来源：'.length).trim();
          } else if (trimmed.startsWith('状态：')) {
            rawPin = trimmed.slice('状态：'.length).trim();
          } else {
            report.extraLines.push(trimmed);
          }
        } else if (section === 'failure' && report.failure !== null && trimmed.startsWith('建议：')) {
          report.failure.advice = trimmed.slice('建议：'.length).trim();
        } else {
          report.extraLines.push(trimmed);
        }
      }
      if (rawPin.startsWith('已固定') || rawSource.includes('手动')) report.title.kind = 'pinned';
      else if (rawSource.includes('回退')) report.title.kind = 'fallback';
      else if (rawSource.includes('自动')) report.title.kind = 'auto';
      else if (rawSource !== '') report.title.sourceLabel = rawSource;

      if (rawPin !== '') {
        report.title.pinStatus = report.title.kind === 'fallback' && !rawPin.includes('尚未生成')
          ? t('dialog.pinState.fallback')
          : rawPin;
      }
      return report;
    }

    /** Minimal observable store for the status modal, requiring no host store SDK. */
    function createDialogStore() {
      let current = null;
      let activeRequestId = 0;
      let activeController = null;
      const listeners = new Set();
      const emit = () => { for (const fn of listeners) fn(); };
      const abortActive = () => {
        if (activeController !== null) {
          try { activeController.abort(); } catch { /* ignore */ }
          activeController = null;
        }
      };
      return {
        get: () => current,
        isCurrent: (requestId) => requestId === activeRequestId,
        beginRequest() {
          abortActive();
          activeRequestId += 1;
          activeController = typeof AbortController === 'function' ? new AbortController() : null;
          return { requestId: activeRequestId, signal: activeController?.signal };
        },
        set(next) { current = next; emit(); },
        close() {
          abortActive();
          activeRequestId += 1;
          if (current !== null) { current = null; emit(); }
        },
        showLoading(requestId, { sessionId, displayTitle }) {
          if (requestId !== activeRequestId) return;
          current = {
            requestId, sessionId, displayTitle,
            loading: true, report: null, error: null,
          };
          emit();
        },
        subscribe(listener) {
          listeners.add(listener);
          return () => { listeners.delete(listener); };
        },
      };
    }

