    /** Format a diagnostic timestamp in the snapshot's time zone when valid. */
    function formatClockTime(timestamp, timezone) {
      if (!Number.isFinite(timestamp)) return undefined;
      try {
        const parts = new Intl.DateTimeFormat('en-US', {
          timeZone: timezone || 'UTC',
          month: '2-digit',
          day: '2-digit',
          hour: '2-digit',
          minute: '2-digit',
          hour12: false,
        }).formatToParts(new Date(timestamp));
        const pick = (type) => parts.find(part => part.type === type)?.value ?? '';
        const month = pick('month');
        const day = pick('day');
        const hour = pick('hour') === '24' ? '00' : pick('hour');
        const minute = pick('minute');
        if (month && day && hour && minute) return `${month}-${day} ${hour}:${minute}`;
      } catch {
        // Ignore invalid timezone values rather than failing modal rendering.
      }
      return undefined;
    }

