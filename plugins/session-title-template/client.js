    /**
     * Build the native menu rows for one Session.
     *
     * Three operations live in one submenu beside the built-in entries, so the
     * main menu keeps its length and each row inherits the native icon column,
     * spacing and disabled styling. Icons use this plugin's own keys on the
     * keyed icon slot so none of them collide visually with the neighbouring
     * built-in Rename (pencil) or Pin Session (pushpin) actions.
     *
     * View status uses `GET session-title-template/status` (supporting both live
     * and persisted cold sessions without opening an agent). Auto-generate
     * prefers `POST session-title-template/refresh` on live sessions so it does
     * not append `/title refresh` cards into the active transcript, falling back
     * to `/title refresh` before a Host reload. Pinning goes through the Session
     * reference, which resumes a cold session when needed.
     */
    function titleMenuActions(target, { t, ctx, statusDialog, refreshingSessions }) {
      const { sessionId, displayTitle } = target;
      const live = (ctx.sessions.retainInfo(sessionId).getSnapshot()?.referenceCount ?? 0) > 0;
      const projected = readProjectedTitleState(ctx, sessionId);
      const hasFetch = typeof fetch === 'function';
      const refreshing = refreshingSessions.has(sessionId);

      const autoDisabledReason = !live
        ? t('menu.needsOpen')
        : refreshing
          ? t('menu.autoBusy')
          : undefined;

      const pinTargetTitle = typeof projected?.title === 'string' && projected.title.trim() !== ''
        ? projected.title
        : (projected === undefined && typeof displayTitle === 'string' && displayTitle.trim() !== '' ? displayTitle : '');
      const pinDisabledReason = projected?.pinned === true
        ? t('menu.alreadyPinned')
        : pinTargetTitle === ''
          ? t('menu.noTitleYet')
          : undefined;

      const statusDisabledReason = !live && !hasFetch ? t('menu.needsOpen') : undefined;

      const runAuto = async () => {
        if (refreshingSessions.has(sessionId)) {
          ctx.contextMenus.notify(t('menu.autoInProgress'), true);
          return;
        }
        refreshingSessions.add(sessionId);
        ctx.contextMenus.notify(t('menu.autoRunning'), true);
        try {
          let fallbackToCommand = true;
          if (hasFetch) {
            try {
              const response = await fetch(REFRESH_ROUTE, {
                method: 'POST',
                headers: { 'content-type': 'application/json', accept: 'application/json' },
                body: JSON.stringify({ sessionId }),
              });
              const payload = await response.json().catch(() => null);
              if (response.ok && typeof payload?.title === 'string') {
                ctx.contextMenus.notify(t('menu.autoDone', { title: payload.title }), true);
                return;
              }
              if (payload && typeof payload.code === 'string') {
                fallbackToCommand = false;
                if (payload.code === 'no-eligible-message') {
                  ctx.contextMenus.notify(t('menu.noEligibleMessage'), false);
                } else if (payload.code === 'session-not-open') {
                  ctx.contextMenus.notify(t('menu.needsOpen'), false);
                } else if (payload.code === 'forbidden') {
                  ctx.contextMenus.notify(t('menu.forbidden'), false);
                } else {
                  const category = typeof payload.category === 'string' ? payload.category : 'Error';
                  ctx.contextMenus.notify(t('menu.autoFailedCategory', { category }), false);
                }
                return;
              }
            } catch {
              // Route unavailable (e.g. Host has not reloaded yet): fall back to `/title refresh`.
            }
          }
          if (!fallbackToCommand) return;
          const result = await ctx.remote.commands.execute(sessionId, '/title refresh', []);
          if (result.ok === false) {
            ctx.contextMenus.notify(result.error?.message || t('menu.autoFailed'), false);
            return;
          }
          const outcome = result.value?.result;
          if (outcome === undefined) {
            ctx.contextMenus.notify(t('menu.unknownCommand'), false);
            return;
          }
          if (outcome.kind === 'error') {
            ctx.contextMenus.notify(String(outcome.text || t('menu.autoFailed')), false);
            return;
          }
          ctx.contextMenus.notify(String(outcome.text ?? t('menu.done')), true);
        } catch (error) {
          ctx.contextMenus.notify(error instanceof Error && error.message ? error.message : t('menu.autoFailed'), false);
        } finally {
          refreshingSessions.delete(sessionId);
        }
      };

      const pin = async () => {
        try {
          const result = await ctx.sessions.using(
            sessionId,
            { source: 'sessionTitleTemplate' },
            reference => reference.binding.session.rename(pinTargetTitle),
          );
          if (result.ok === false) {
            ctx.contextMenus.notify(result.error?.message || t('menu.pinFailed'), false);
            return;
          }
          ctx.contextMenus.notify(t('menu.pinDone'), true);
        } catch (error) {
          ctx.contextMenus.notify(error instanceof Error && error.message ? error.message : t('menu.pinFailed'), false);
        }
      };

      const readStatus = async (signal) => {
        // Prefer the Host's read-only HTTP route so opening the modal never
        // appends `/title status` command events into the live chat transcript
        // and works for cold sessions too.
        if (hasFetch) {
          try {
            const response = await fetch(`${STATUS_ROUTE}?sessionId=${encodeURIComponent(sessionId)}`, {
              headers: { accept: 'application/json' },
              ...(signal === undefined ? {} : { signal }),
            });
            const payload = await response.json().catch(() => null);
            if (response.ok) {
              if (payload?.snapshot !== null && typeof payload?.snapshot === 'object') {
                return reportFromSnapshot(payload.snapshot, t);
              }
              if (typeof payload?.text === 'string') {
                return parseStatusReport(payload.text, t);
              }
            }
            // Structured error from our own route: surface directly instead of
            // falling back and polluting the chat transcript with `/title status`.
            if (payload && typeof payload.code === 'string') {
              const codeError = new Error(
                payload.code === 'session-not-open' ? t('menu.needsOpen')
                  : payload.code === 'session-not-found' ? t('menu.sessionNotFound')
                    : payload.code === 'forbidden' ? t('menu.forbidden')
                      : t('menu.statusFailed'),
              );
              codeError.routeHandled = true;
              throw codeError;
            }
          } catch (error) {
            if (signal?.aborted || error?.name === 'AbortError') throw error;
            if (error?.routeHandled === true) throw error;
            // Route unavailable (e.g. Host has not reloaded yet): fall back to `/title status` for live sessions.
          }
        }
        if (!live) throw new Error(t('menu.needsOpen'));
        const result = await ctx.remote.commands.execute(sessionId, '/title status', []);
        if (result.ok === false) throw new Error(result.error.message);
        const outcome = result.value?.result;
        if (outcome === undefined) throw new Error(t('menu.unknownCommand'));
        if (outcome.kind === 'error') throw new Error(outcome.text);
        return parseStatusReport(String(outcome.text ?? ''), t);
      };

      const openStatus = async () => {
        const { requestId, signal } = statusDialog.beginRequest();
        // Wait briefly before showing a loading placeholder so local reads open
        // directly at their final height without a loading-to-content jump.
        const loadingTimer = typeof setTimeout === 'function'
          ? setTimeout(() => { statusDialog.showLoading(requestId, { sessionId, displayTitle }); }, 180)
          : undefined;
        try {
          const report = await readStatus(signal);
          if (loadingTimer !== undefined && typeof clearTimeout === 'function') clearTimeout(loadingTimer);
          if (!statusDialog.isCurrent(requestId)) return;
          statusDialog.set({
            requestId, sessionId, displayTitle, loading: false,
            report, error: null,
          });
        } catch (error) {
          if (loadingTimer !== undefined && typeof clearTimeout === 'function') clearTimeout(loadingTimer);
          if (!statusDialog.isCurrent(requestId)) return;
          statusDialog.set({
            requestId, sessionId, displayTitle, loading: false,
            report: null,
            error: error instanceof Error && error.message ? error.message : t('menu.statusFailed'),
          });
        }
      };

      return [{
        id: 'title',
        label: t('menu.title'),
        icon: { key: 'session-title-template.title' },
        // The submenu is always offered; individual rows carry the reason they
        // are unavailable, which is more discoverable than an empty menu.
        children: [
          {
            id: 'title.auto',
            label: disabledLabel(t, 'menu.auto', autoDisabledReason),
            icon: { key: 'session-title-template.auto' },
            disabled: autoDisabledReason !== undefined,
            ...(autoDisabledReason === undefined ? { run: runAuto } : {}),
            failureLabel: t('menu.autoFailed'),
          },
          {
            id: 'title.pin',
            label: disabledLabel(t, 'menu.pin', pinDisabledReason),
            icon: { key: 'session-title-template.pin' },
            disabled: pinDisabledReason !== undefined,
            ...(pinDisabledReason === undefined ? { run: pin } : {}),
            failureLabel: t('menu.pinFailed'),
          },
          {
            id: 'title.status',
            label: disabledLabel(t, 'menu.status', statusDisabledReason),
            icon: { key: 'session-title-template.status' },
            disabled: statusDisabledReason !== undefined,
            ...(statusDisabledReason === undefined ? { run: openStatus } : {}),
            failureLabel: t('menu.statusFailed'),
          },
        ],
      }];
    }

